#pragma once
#include "player/Player.h"

// ============================================================
// 化学学院学生（玩家派生类）
// 继承自 Player 基类
// 
// 职业特点：
// - 生命值厚（能承受更多伤害）
// - 防御力高（减少受到的伤害）
// - 代表色：化学绿（#4CAF50）
// 
// 属性成长：
// - 等级提升时，生命值和防御力增长较快
// - 攻击力和速度增长较慢
// 
// 职业定位：坦克/肉盾型角色，适合抗伤害、保护队友
// ============================================================
class ChemPlayer : public Player {
public:
    /**
     * @brief 构造函数
     * 调用父类构造函数，设置玩家类型为 Chem，名称为 "Chemistry Student"
     */
    ChemPlayer();
    
    /**
     * @brief 析构函数
     * 默认实现，确保正确释放资源
     */
    ~ChemPlayer() override = default;

    /**
     * @brief 初始化属性
     * 设置初始属性值：
     * - 生命值：较高
     * - 攻击力：较低
     * - 防御力：较高
     * - 移动速度：较低
     * - 暴击率：较低
     * - 代表色：化学绿
     */
    void init() override;
    
    /**
     * @brief 更新玩家状态
     * @param dt 时间增量（秒）
     * 处理化学学生特有的状态更新逻辑，如药剂效果等
     */
    void update(float dt) override;
    
    /**
     * @brief 执行攻击
     * 实现化学学生的攻击逻辑，可能使用试剂或爆炸类攻击
     */
    void attack() override;
};
